"""Картки на воду (Petroline): не пальне, на сторінці «Карти» типово приховані.

Правило автоматичної позначки: у назві картки (ім'я водія/транспорту в Petroline, наші Авто чи ПІБ)
є окреме слово «вода» («води», «воду») без різниці великих/малих літер. «Водій», «водний» тощо — ні.
Перевірено на реальних даних 2026-11-10: усі 99 таких карток — водії, яким у Petroline дозволено лише
омивач (15) або омивач і воду (17), жодна не має пального.
Менеджер може поставити/зняти позначку вручну — тоді синхронізація її більше не змінює (`is_water_manual`).
Копія виразу — у міграції 0013 (міграції не залежать від коду застосунку).
"""

import re

# Слово не має бути частиною іншого: перед і після — не літера (цифри, «_», пробіл, «|» — можна)
WATER_WORD = re.compile(r"(?<![^\W\d_])вод[аиу](?![^\W\d_])", re.IGNORECASE)


def has_water_word(*texts: str | None) -> bool:
    """Чи є в будь-якому з текстів окреме слово «вода» / «води» / «воду»."""
    return any(WATER_WORD.search(text or "") for text in texts)
